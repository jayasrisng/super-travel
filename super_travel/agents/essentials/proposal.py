"""Deterministic Travel Essentials proposals for the control API (no model call).

Facts come from curated static data (country_info.json), the ECB exchange rate and the
mock eSIM catalogue. Nothing here is generated by a model.
"""

from __future__ import annotations

import json
from datetime import timedelta

from super_travel.agents.essentials import tools
from super_travel.control.schemas import EssentialsInput, EssentialsProposal
from super_travel.core.geo import destination
from super_travel.core.tools.fx import fetch_rate

STATIC_SOURCE = "https://github.com/jayasrisng/super-travel/blob/main/super_travel/agents/essentials/data/country_info.json"
FX_SOURCE = "https://api.frankfurter.dev/v1/latest"


class EssentialsProposalAgent:
    name = "essentials"

    def __init__(self, mode="fixture", rate_fn=None):
        self.mode = mode
        self.rate_fn = rate_fn  # None -> live ECB rate, looked up at call time

    def propose(self, request: EssentialsInput, now) -> EssentialsProposal:
        place = destination(request.destination)
        info = json.loads(tools.get_country_info(place["country"])) if place else {"error": True}
        if not place or "error" in info:
            return EssentialsProposal(
                reply=f"We don't have reference data for {request.destination} yet. Check the official government travel advice for this destination.",
                assumptions=["No curated country data for this destination."],
                sources=[], data_mode="fixture", sections=[], emergency_contacts=[],
                exchange_rate=None, connectivity_options=[], checklist_tasks=[],
            )

        country, local = place["country"], info["currency"]
        kids = request.child_count + request.infant_count
        assumptions = [
            "Facts come from Wonder's curated country data; advisories, entry rules and health notices are not included and must be checked with official sources.",
            "eSIM plans are mock catalogue data.",
        ]
        sources = [{"provider": "wonder-country-data", "source_url": STATIC_SOURCE, "observed_at": now,
                    "data_mode": "manual", "availability": "not_applicable", "cost_status": "unknown"}]

        rate = None
        if request.home_currency != local:
            try:
                value, as_of = (self.rate_fn or fetch_rate)(local, request.home_currency)
                rate = {"from_currency": local, "to_currency": request.home_currency, "rate": round(value, 4), "as_of": as_of}
                sources.append({"provider": "ecb-via-frankfurter", "source_url": FX_SOURCE, "observed_at": now,
                                "data_mode": "live", "availability": "not_applicable", "cost_status": "verified"})
            except Exception:  # noqa: BLE001 - network is optional; say so instead of failing
                assumptions.append("Exchange rate unavailable right now; check before travelling.")

        days = (request.end_date - request.start_date).days + 1 if request.start_date and request.end_date else 7
        plans = json.loads(tools.find_esim_plans([country], days))["plans"][:3]
        options = [{"item_id": f"esim-{p['id']}", "provider": p["provider"], "data": f"{p['data_gb']} GB" if isinstance(p["data_gb"], (int, float)) else str(p["data_gb"]),
                    "days": p["days"], "price": {"amount_minor": round(p["price_usd"] * 100), "currency": "USD"}} for p in plans]

        def item(key, title, detail, priority="should"):
            return {"item_id": key, "title": title, "detail": detail, "priority": priority}

        money = [item("money-local", f"Pay in {local}", f"{info['name']} uses {local}. When a card terminal offers to charge in {request.home_currency}, choose {local}: the conversion is usually worse.", "must"),
                 item("money-tipping", "Tipping", info["tipping"], "nice")]
        if rate:
            money.insert(1, item("money-rate", "Exchange rate", f"1 {local} ≈ {rate['rate']:.2f} {request.home_currency} (ECB reference, {rate['as_of']}). Card and ATM rates are usually 1–3% worse."))
        connectivity = [item("conn-plugs", f"Plugs {'/'.join(info['plug_types'])}, {info['voltage']}V", f"Bring adapters for type {' or '.join(info['plug_types'])} sockets; check that chargers accept {info['voltage']}V.", "must")]
        if options:
            o = options[0]
            connectivity.append(item("conn-esim", "Get an eSIM", f"{o['provider']}: {o['data']} for {o['days']} days at ${o['price']['amount_minor'] / 100:.2f}. Install before the flight."))
        health = [item("health-water", "Tap water", info["tap_water"], "nice")]
        if kids:
            health.append(item("health-kids", "Children's medicines", "Pack children's usual medicines in original packaging with dosing instructions, plus a thermometer.", "must"))
        insurance = [item("ins-cover", "Travel insurance", f"Choose a policy with medical, trip-delay and baggage-delay cover{f' that names all {request.adult_count + kids} travelers' if kids else ''}.", "must")]
        emergency_number = info["emergency"].get("general") or next(iter(info["emergency"].values()))
        safety = [item("safety-number", f"Emergency: {emergency_number}", f"Save {emergency_number} in everyone's phone{', and teach it to the kids' if kids else ''}.", "must")]
        language = [item("lang-main", "Languages", ", ".join(info["languages"]) + ". A few words of greeting and thanks go a long way.", "nice")]

        start = request.start_date
        tasks = []
        if start:
            tasks = [
                {"item_id": "ess-insurance", "title": "Buy travel insurance", "system": "travel_essentials", "due_date": start - timedelta(days=10), "priority": "must"},
                {"item_id": "ess-adapters", "title": f"Get plug adapters (type {'/'.join(info['plug_types'])})", "system": "travel_essentials", "due_date": start - timedelta(days=5), "priority": "should"},
                {"item_id": "ess-esim", "title": "Install eSIM before the flight", "system": "travel_essentials", "due_date": start - timedelta(days=1), "priority": "should"},
            ]

        return EssentialsProposal(
            reply=f"Pre-departure briefing for {info['name']}: pay in {local}, use type {'/'.join(info['plug_types'])} plugs, and save {emergency_number} for emergencies.",
            assumptions=assumptions, sources=sources, data_mode="fixture",
            sections=[{"topic": "payments_currency", "items": money}, {"topic": "connectivity", "items": connectivity},
                      {"topic": "health", "items": health}, {"topic": "insurance", "items": insurance},
                      {"topic": "safety", "items": safety}, {"topic": "language", "items": language}],
            emergency_contacts=[{"country_code": country, "label": label.replace("_", " ").capitalize(), "phone": phone} for label, phone in info["emergency"].items()],
            exchange_rate=rate, connectivity_options=options, checklist_tasks=tasks,
        )
